#!/usr/bin/env python3
"""Generate src-tauri/src/pdf/font_metrics.rs from URW base35 AFM files.

Development-time tool only; PaperFlow does not run Python at runtime.
The URW fonts are metric-compatible with the PDF standard 14 fonts, so their
advance widths position text drawn with Helvetica, Times and Courier exactly.

Usage: python3 scripts/gen-font-metrics.py > src-tauri/src/pdf/font_metrics.rs
"""
import glob
import re
import sys

AFM_DIR = "/usr/share/fonts/type1/urw-base35"
FONTS = [
    ("HELVETICA", "NimbusSans-Regular"),
    ("HELVETICA_BOLD", "NimbusSans-Bold"),
    ("TIMES_ROMAN", "NimbusRoman-Regular"),
    ("TIMES_BOLD", "NimbusRoman-Bold"),
    ("COURIER", "NimbusMonoPS-Regular"),
    ("COURIER_BOLD", "NimbusMonoPS-Bold"),
]

agl_path = glob.glob("/usr/share/ghostscript/*/Resource/Init/gs_agl.ps")[0]
unicode_to_name = {}
with open(agl_path, encoding="latin-1") as fh:
    for line in fh:
        m = re.match(r"^/(\S+) 16#([0-9A-F]{4})$", line.strip())
        if m:
            unicode_to_name.setdefault(int(m.group(2), 16), m.group(1))
# Names the AFMs use that differ from the first AGL entry.
OVERRIDES = {0x00A0: "space", 0x00AD: "hyphen", 0x0020: "space", 0x002D: "hyphen"}


def load_widths(name):
    widths = {}
    with open(f"{AFM_DIR}/{name}.afm", encoding="latin-1") as fh:
        for line in fh:
            m = re.match(r"C (-?\d+) ; WX (\d+) ; N (\S+) ;", line)
            if m:
                widths[m.group(3)] = int(m.group(2))
    return widths


out = sys.stdout
out.write("// @generated by scripts/gen-font-metrics.py from the URW base35 AFM files.\n")
out.write("// Advance widths (1/1000 em) for WinAnsiEncoding codes 32..=255.\n")
out.write("// A width of 0 marks a code with no glyph.\n\n")
for const, afm in FONTS:
    widths = load_widths(afm)
    row = []
    for code in range(32, 256):
        try:
            ch = bytes([code]).decode("cp1252")
        except UnicodeDecodeError:
            row.append(0)
            continue
        cp = ord(ch)
        glyph = OVERRIDES.get(cp) or unicode_to_name.get(cp)
        row.append(widths.get(glyph, 0) if glyph else 0)
    out.write(f"pub const {const}: [u16; 224] = [\n")
    for i in range(0, 224, 16):
        out.write("    " + ", ".join(str(w) for w in row[i : i + 16]) + ",\n")
    out.write("];\n\n")
